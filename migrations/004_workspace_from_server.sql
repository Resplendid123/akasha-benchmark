-- 删掉 connection.workspace_id。
--
-- 它是个设计错误：workspace 由**服务端**决定，客户端选不了。自建部署走
-- workspaceRepo.findFirst()（domain.middleware.ts:18），所以那一项的权威值只能在
-- 登录之后从 users/me 读出来。
--
-- 让用户手填它带来的是纯负面：填错了闸门会误报，而我为此还加过一段
-- 「改 workspace_id 会影响已入库的层」的警告 —— 那是在给一个不该存在的字段
-- 打补丁。
--
-- index_layer.workspace_id **保留**：那是「这一层入库时实际在哪个 workspace」，
-- 由 ingest 从 users/me 写入，是真实的事实而不是一个待填的配置。
--
-- 代价说明白：闸门从此不能离线判了。index_layer_readiness 是纯库函数，登不了
-- Akasha，所以 workspace 比对挪到 ingest / query 登录之后。两者都在发出任何
-- 写入或查询之前就会拦住，所以拦截时机没变；变的是判据来源 ——
-- 从「用户填的那个值」变成「服务端说的那个值」。
--
-- ensure_space 的 space 身份校验不受影响（它比的是 space_id），
-- 而那一道本来就是更强的：同 slug 不等于同一个 space。

ALTER TABLE connection DROP COLUMN workspace_id;
